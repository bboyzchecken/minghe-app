/**
 * ชนิดข้อมูลของตาราง "จุดที่ควรบริหาร" (F-24)
 *
 * ⚠️ สถานะ: ไฟล์นี้เป็น **โครงจาก T0-4** — มีแต่ `type` ยังไม่มีเนื้อกฎ
 * กรอบที่ อ.เม ให้มาแล้ว: แสดง **5–8 ข้อ เรียงตามความรุนแรง**
 * แต่ **เนื้อกฎ 15–20 ข้อยังรอท่านอยู่** (ดู spec-round2-readiness-plan.md §3.3)
 * แผนที่ตกลงกันไว้: ทีมร่างตัวอย่าง 5–8 ข้อส่งให้ท่านแก้ แทนการรอให้ท่านเขียนใหม่ทั้งชุด (ข้อ 5.1)
 */

/** ความรุนแรงของประเด็น — ใช้เรียงลำดับก่อนตัดให้เหลือ 5–8 ข้อ */
export type RuleSeverity = 'high' | 'medium' | 'low'

/** ลำดับความรุนแรงจากมากไปน้อย — ใช้ sort */
export const SEVERITY_ORDER: RuleSeverity[] = ['high', 'medium', 'low']

/** จำนวนข้อที่แสดงต่อรายงานหนึ่งใบ ตามกรอบที่ อ.เม กำหนด */
export const MIN_RULES_SHOWN = 5
export const MAX_RULES_SHOWN = 8

export interface ManagementRule {
  id: string
  severity: RuleSeverity
  titleTh: string
  /** คำอธิบายเชิงการทำงาน — ห้ามใช้ภาษาชี้ชะตา (Anti-Fatalism Rule) */
  explanationTh: string
  /**
   * คำถามชวนคิดปิดท้าย — บังคับมีทุกข้อ ตามโจทย์ 6.2 ที่ อ.เม เพิ่มมา
   * (ทุกส่วนต้องมีน้ำเสียงให้กำลังใจ และปิดท้ายด้วยคำถามชวนคิด)
   */
  reflectionQuestionTh: string
  /**
   * เงื่อนไขที่ทำให้กฎข้อนี้ทำงาน
   * ยังเป็น `string` อธิบายด้วยภาษาคนไปก่อน — จะกลายเป็น predicate จริง
   * เมื่อได้เนื้อกฎจาก อ.เม แล้ว
   */
  conditionTh: string
}
