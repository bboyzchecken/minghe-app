// TimezoneGuess คือผลการเดาเขตเวลาพร้อมที่มา เพื่อให้หน้าเว็บบอกผู้ใช้ได้ว่าเดามาจากอะไร
type TimezoneGuess struct {
	OffsetHours float64 `json:"offset_hours"`
	Region      string  `json:"region"`
	// Approximate = เดาจากลองจิจูดล้วน ยังไม่ได้ยืนยันกับภูมิภาคใด → หน้าเว็บควรเตือนให้ตรวจ
	Approximate bool `json:"approximate"`
}

// GuessTimezone คืนเขตเวลาตั้งต้นของพิกัดหนึ่ง ๆ
func GuessTimezone(lat, lng float64) TimezoneGuess {
	for _, box := range tzBoxes {
		if lat >= box.minLat && lat <= box.maxLat && lng >= box.minLng && lng <= box.maxLng {
			return TimezoneGuess{OffsetHours: box.offset, Region: box.label}
		}
	}
	// นอกตาราง — ใช้เขตเวลาตามภูมิศาสตร์ (15° ต่อชั่วโมง) แล้วบอกให้ผู้ใช้ตรวจเอง
	offset := float64(int(lng/15.0 + sign(lng)*0.5))
	if offset > 14 {
		offset = 14
	}
	if offset < -12 {
		offset = -12
	}
	return TimezoneGuess{OffsetHours: offset, Region: "", Approximate: true}
}

func sign(v float64) float64 {
	if v < 0 {
		return -1
	}
	return 1
}
